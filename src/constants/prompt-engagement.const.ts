/** 男频/女频爽感侧重（仍禁廉价词） */
export function buildAudienceEngagementOverlay(
  audience: 'male' | 'female',
): string {
  if (audience === 'male') {
    return `【受众爽感 · 男频】
快反馈优先：算路落子、信息差、规则内赢回话语权；反派宜聪明、主角宜有分寸。
开场与每回合尽早给出「可操作的胜负手」，而非 prolonged 心理独白。`;
  }
  return `【受众爽感 · 女频】
快反馈优先：边界、偏袒、误会、选择与拒绝的即时后果；情感张力宜在细节里爆发，不拖长虐。
开场与每回合尽早给出「关系位移」或「自我价值确认」，而非 prolonged 旁白铺垫。`;
}
